export const THEMES: ThemeContent[] = [MANOR_THEME, FARM_THEME, CAMP_THEME, MESS_HALL_THEME];

/** Looks a theme pack up by its @kdp/shared theme id, falling back to the manor. */
export function themeById(id: string | undefined): ThemeContent {
  return THEMES.find((theme) => theme.id === id) ?? MANOR_THEME;
}
