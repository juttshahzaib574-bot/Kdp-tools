// Theme content packs. The generator/solver code never changes to add a
// theme — only this data grows. Each pack needs enough names to cover the
// largest supported grid (8 suspects) with room to shuffle, and enough
// objects to give every suspect a distinct one.
export interface ThemeContent {
  /** Stable id, matched against MYSTERY_THEMES in @kdp/shared. */
  id: string;
  name: string;
  roomNames: string[];
  landmarkNames: string[];
  suspectFirstNames: string[];
  suspectLastNames: string[];
  /**
   * The evidence layer's object pool — every suspect carries exactly one
   * distinct entry. Needs at least as many entries as the largest grid
   * size, and reads best when the objects are plausible murder weapons
   * for the setting.
   */
  objectNames: string[];
}

